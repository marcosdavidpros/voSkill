-- Run once after 001_initial_schema.sql, connected as ITB2CTRF.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    L_SESSION_USER VARCHAR2(128);
    L_COLLISIONS PLS_INTEGER;
BEGIN
    L_SESSION_USER := SYS_CONTEXT('USERENV', 'SESSION_USER');
    IF UPPER(L_SESSION_USER) <> 'ITB2CTRF' THEN
        RAISE_APPLICATION_ERROR(-20010, 'Connect as ITB2CTRF before creating voSkill objects');
    END IF;

    SELECT COUNT(*)
      INTO L_COLLISIONS
      FROM USER_OBJECTS
     WHERE OBJECT_NAME IN (
        'VSK_SCENARIO_SNAPSHOTS',
        'VSK_SCENARIOS',
        'VSK_TRG_SCN_SNAPSHOT_IMM',
        'VSK_IX_SCN_PROJECT',
        'VSK_IX_SCN_BASE'
     );

    IF L_COLLISIONS > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Scenario objects already exist; inspect USER_OBJECTS');
    END IF;
END;
/

CREATE TABLE VSK_SCENARIO_SNAPSHOTS (
    SNAPSHOT_ID VARCHAR2(36 CHAR) NOT NULL,
    PROJECT_ID VARCHAR2(36 CHAR) NOT NULL,
    SNAPSHOT_JSON CLOB NOT NULL,
    SNAPSHOT_SHA256 VARCHAR2(64 CHAR) NOT NULL,
    CREATED_BY VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT VSK_PK_SCN_SNAPSHOT PRIMARY KEY (SNAPSHOT_ID),
    CONSTRAINT VSK_FK_SCN_SNAP_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES VSK_PROJECTS (PROJECT_ID),
    CONSTRAINT VSK_CK_SCN_SNAP_JSON CHECK (SNAPSHOT_JSON IS JSON),
    CONSTRAINT VSK_CK_SCN_SNAP_HASH CHECK (LENGTH(SNAPSHOT_SHA256) = 64)
);

CREATE TABLE VSK_SCENARIOS (
    SCENARIO_ID VARCHAR2(36 CHAR) NOT NULL,
    PROJECT_ID VARCHAR2(36 CHAR) NOT NULL,
    SNAPSHOT_ID VARCHAR2(36 CHAR) NOT NULL,
    BASE_SCENARIO_ID VARCHAR2(36 CHAR),
    SCENARIO_TYPE VARCHAR2(16 CHAR) NOT NULL,
    SCENARIO_NAME VARCHAR2(200 CHAR) NOT NULL,
    DELTAS_JSON CLOB DEFAULT '{}' NOT NULL,
    ACTOR_ID VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT VSK_PK_SCENARIOS PRIMARY KEY (SCENARIO_ID),
    CONSTRAINT VSK_FK_SCN_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES VSK_PROJECTS (PROJECT_ID),
    CONSTRAINT VSK_FK_SCN_SNAPSHOT FOREIGN KEY (SNAPSHOT_ID)
        REFERENCES VSK_SCENARIO_SNAPSHOTS (SNAPSHOT_ID),
    CONSTRAINT VSK_UQ_SCN_BASE_REF UNIQUE (SCENARIO_ID, PROJECT_ID, SNAPSHOT_ID),
    CONSTRAINT VSK_FK_SCN_BASE FOREIGN KEY (BASE_SCENARIO_ID, PROJECT_ID, SNAPSHOT_ID)
        REFERENCES VSK_SCENARIOS (SCENARIO_ID, PROJECT_ID, SNAPSHOT_ID),
    CONSTRAINT VSK_UQ_SCN_PROJECT_NAME UNIQUE (PROJECT_ID, SCENARIO_NAME),
    CONSTRAINT VSK_CK_SCN_TYPE CHECK (SCENARIO_TYPE IN ('BASE', 'ALTERNATIVE')),
    CONSTRAINT VSK_CK_SCN_BASE CHECK (
        (SCENARIO_TYPE = 'BASE' AND BASE_SCENARIO_ID IS NULL)
        OR (SCENARIO_TYPE = 'ALTERNATIVE' AND BASE_SCENARIO_ID IS NOT NULL)
    ),
    CONSTRAINT VSK_CK_SCN_DELTAS_JSON CHECK (DELTAS_JSON IS JSON)
);

CREATE INDEX VSK_IX_SCN_PROJECT ON VSK_SCENARIOS (PROJECT_ID, CREATED_AT);
CREATE INDEX VSK_IX_SCN_BASE ON VSK_SCENARIOS (BASE_SCENARIO_ID);

CREATE OR REPLACE TRIGGER VSK_TRG_SCN_SNAPSHOT_IMM
BEFORE UPDATE OR DELETE ON VSK_SCENARIO_SNAPSHOTS
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20020, 'Scenario snapshots are immutable');
END;
