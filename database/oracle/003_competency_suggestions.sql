-- Run once after 001_initial_schema.sql, connected as ITB2CTRF.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    L_SESSION_USER VARCHAR2(128);
    L_COLLISIONS PLS_INTEGER;
BEGIN
    L_SESSION_USER := SYS_CONTEXT('USERENV', 'SESSION_USER');
    IF UPPER(L_SESSION_USER) <> 'ITB2CTRF' THEN
        RAISE_APPLICATION_ERROR(-20010, 'Connect as ITB2CTRF before creating voSkill objects');
    END IF;

    SELECT COUNT(*)
      INTO L_COLLISIONS
      FROM USER_OBJECTS
     WHERE OBJECT_NAME IN (
        'VSK_SKILL_SUGGESTIONS',
        'VSK_IX_SUG_PERSON_STATUS',
        'VSK_IX_SUG_CREATED_AT'
     );

    IF L_COLLISIONS > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Suggestion objects already exist; inspect USER_OBJECTS');
    END IF;
END;
/

CREATE TABLE VSK_SKILL_SUGGESTIONS (
    SUGGESTION_ID VARCHAR2(36 CHAR) NOT NULL,
    PERSON_ID VARCHAR2(36 CHAR) NOT NULL,
    SUGGESTED_SKILL_NAME VARCHAR2(150 CHAR) NOT NULL,
    SUGGESTED_LEVEL NUMBER(1) NOT NULL,
    CONFIDENCE NUMBER(4, 3) NOT NULL,
    EVIDENCE_SPAN VARCHAR2(4000 CHAR) NOT NULL,
    SOURCE_SHA256 VARCHAR2(64 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING_REVIEW' NOT NULL,
    CREATED_BY VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_BY VARCHAR2(36 CHAR),
    REVIEWED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT VSK_PK_SKILL_SUGGESTIONS PRIMARY KEY (SUGGESTION_ID),
    CONSTRAINT VSK_FK_SUG_PERSON FOREIGN KEY (PERSON_ID)
        REFERENCES VSK_PERSONS (PERSON_ID),
    CONSTRAINT VSK_CK_SUG_LEVEL CHECK (SUGGESTED_LEVEL BETWEEN 1 AND 5),
    CONSTRAINT VSK_CK_SUG_CONFIDENCE CHECK (CONFIDENCE BETWEEN 0 AND 1),
    CONSTRAINT VSK_CK_SUG_SPAN CHECK (LENGTH(TRIM(EVIDENCE_SPAN)) > 0),
    CONSTRAINT VSK_CK_SUG_HASH CHECK (LENGTH(SOURCE_SHA256) = 64),
    CONSTRAINT VSK_CK_SUG_STATUS CHECK (
        STATUS IN ('PENDING_REVIEW', 'ACCEPTED', 'EDITED', 'REJECTED')
    )
);

CREATE INDEX VSK_IX_SUG_PERSON_STATUS
    ON VSK_SKILL_SUGGESTIONS (PERSON_ID, STATUS);
CREATE INDEX VSK_IX_SUG_CREATED_AT
    ON VSK_SKILL_SUGGESTIONS (CREATED_AT);