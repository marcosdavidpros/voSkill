-- Run once after 003_competency_suggestions.sql, connected as ITB2CTRF.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    L_SESSION_USER VARCHAR2(128);
    L_EXISTING_COLUMNS PLS_INTEGER;
    L_EXISTING_CONSTRAINTS PLS_INTEGER;
BEGIN
    L_SESSION_USER := SYS_CONTEXT('USERENV', 'SESSION_USER');
    IF UPPER(L_SESSION_USER) <> 'ITB2CTRF' THEN
        RAISE_APPLICATION_ERROR(-20010, 'Connect as ITB2CTRF before altering voSkill objects');
    END IF;

    SELECT COUNT(*)
      INTO L_EXISTING_COLUMNS
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'VSK_SKILL_SUGGESTIONS'
       AND COLUMN_NAME IN ('REVIEWED_LEVEL', 'REVIEWED_EVIDENCE', 'COMPETENCY_ID');

    SELECT COUNT(*)
      INTO L_EXISTING_CONSTRAINTS
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME IN ('VSK_FK_SUG_COMPETENCY', 'VSK_CK_SUG_REVIEW_STATE');

    IF L_EXISTING_COLUMNS > 0 OR L_EXISTING_CONSTRAINTS > 0 THEN
        RAISE_APPLICATION_ERROR(-20012, 'Review columns or constraints already exist; inspect metadata');
    END IF;
END;
/

ALTER TABLE VSK_SKILL_SUGGESTIONS ADD (
    REVIEWED_LEVEL NUMBER(1),
    REVIEWED_EVIDENCE VARCHAR2(4000 CHAR),
    COMPETENCY_ID VARCHAR2(36 CHAR)
);

ALTER TABLE VSK_SKILL_SUGGESTIONS ADD CONSTRAINT VSK_FK_SUG_COMPETENCY
    FOREIGN KEY (COMPETENCY_ID) REFERENCES VSK_PERSON_COMPETENCIES (COMPETENCY_ID);

ALTER TABLE VSK_SKILL_SUGGESTIONS ADD CONSTRAINT VSK_CK_SUG_REVIEW_STATE CHECK (
    (STATUS IN ('PENDING_REVIEW', 'REJECTED')
        AND REVIEWED_LEVEL IS NULL
        AND REVIEWED_EVIDENCE IS NULL
        AND COMPETENCY_ID IS NULL)
    OR
    (STATUS IN ('ACCEPTED', 'EDITED')
        AND REVIEWED_LEVEL BETWEEN 1 AND 5
        AND REVIEWED_EVIDENCE IS NOT NULL
        AND COMPETENCY_ID IS NOT NULL)
);