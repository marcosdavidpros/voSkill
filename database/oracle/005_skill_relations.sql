-- Run once after 001_initial_schema.sql, connected as ITB2CTRF.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    L_SESSION_USER VARCHAR2(128);
    L_COLLISIONS PLS_INTEGER;
BEGIN
    L_SESSION_USER := SYS_CONTEXT('USERENV', 'SESSION_USER');
    IF UPPER(L_SESSION_USER) <> 'ITB2CTRF' THEN
        RAISE_APPLICATION_ERROR(-20010, 'Connect as ITB2CTRF before creating voSkill objects');
    END IF;

    SELECT COUNT(*)
      INTO L_COLLISIONS
      FROM USER_OBJECTS
     WHERE OBJECT_NAME IN (
        'VSK_SKILL_RELATIONS',
        'VSK_IX_SR_TARGET'
     );

    IF L_COLLISIONS > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Skill relation objects already exist; inspect USER_OBJECTS');
    END IF;
END;
/

CREATE TABLE VSK_SKILL_RELATIONS (
    RELATION_ID VARCHAR2(36 CHAR) NOT NULL,
    SOURCE_SKILL_ID VARCHAR2(36 CHAR) NOT NULL,
    TARGET_SKILL_ID VARCHAR2(36 CHAR) NOT NULL,
    CONFIDENCE NUMBER(4, 3) NOT NULL,
    ACTIVE_FLAG CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    ACTOR_ID VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT VSK_PK_SKILL_RELATIONS PRIMARY KEY (RELATION_ID),
    CONSTRAINT VSK_FK_SR_SOURCE FOREIGN KEY (SOURCE_SKILL_ID)
        REFERENCES VSK_SKILLS (SKILL_ID),
    CONSTRAINT VSK_FK_SR_TARGET FOREIGN KEY (TARGET_SKILL_ID)
        REFERENCES VSK_SKILLS (SKILL_ID),
    CONSTRAINT VSK_UQ_SR_PAIR UNIQUE (SOURCE_SKILL_ID, TARGET_SKILL_ID),
    CONSTRAINT VSK_CK_SR_CONFIDENCE CHECK (CONFIDENCE BETWEEN 0 AND 1),
    CONSTRAINT VSK_CK_SR_ACTIVE CHECK (ACTIVE_FLAG IN ('Y', 'N')),
    CONSTRAINT VSK_CK_SR_NOT_SELF CHECK (SOURCE_SKILL_ID <> TARGET_SKILL_ID)
);

CREATE INDEX VSK_IX_SR_TARGET ON VSK_SKILL_RELATIONS (TARGET_SKILL_ID, ACTIVE_FLAG);