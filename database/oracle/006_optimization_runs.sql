-- Run once after 005_skill_relations.sql, connected as ITB2CTRF.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    L_SESSION_USER VARCHAR2(128);
    L_COLLISIONS PLS_INTEGER;
BEGIN
    L_SESSION_USER := SYS_CONTEXT('USERENV', 'SESSION_USER');
    IF UPPER(L_SESSION_USER) <> 'ITB2CTRF' THEN
        RAISE_APPLICATION_ERROR(-20010, 'Connect as ITB2CTRF before creating voSkill objects');
    END IF;

    SELECT COUNT(*)
      INTO L_COLLISIONS
      FROM USER_OBJECTS
     WHERE OBJECT_NAME IN (
        'VSK_OPTIMIZATION_RUNS',
        'VSK_IX_OPT_RUN_SNAPSHOT'
     );

    IF L_COLLISIONS > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Optimization run objects already exist; inspect USER_OBJECTS');
    END IF;
END;
/

CREATE TABLE VSK_OPTIMIZATION_RUNS (
    RUN_ID VARCHAR2(36 CHAR) NOT NULL,
    SNAPSHOT_HASH CHAR(64 CHAR) NOT NULL,
    ALGORITHM_VERSION VARCHAR2(64 CHAR) NOT NULL,
    CONFIGURATION_JSON CLOB NOT NULL,
    SEED NUMBER(10, 0) NOT NULL,
    ALTERNATIVES_HASH CHAR(64 CHAR) NOT NULL,
    RESULT_JSON CLOB NOT NULL,
    ACTOR_ID VARCHAR2(36 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT VSK_PK_OPT_RUNS PRIMARY KEY (RUN_ID),
    CONSTRAINT VSK_CK_OPT_RUN_SEED CHECK (SEED >= 0)
);

CREATE INDEX VSK_IX_OPT_RUN_SNAPSHOT ON VSK_OPTIMIZATION_RUNS (SNAPSHOT_HASH);