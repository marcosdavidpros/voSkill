-- Run once after 006_optimization_runs.sql, connected as ITB2CTRF.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    L_SESSION_USER VARCHAR2(128);
    L_COLLISIONS PLS_INTEGER;
BEGIN
    L_SESSION_USER := SYS_CONTEXT('USERENV', 'SESSION_USER');
    IF UPPER(L_SESSION_USER) <> 'ITB2CTRF' THEN
        RAISE_APPLICATION_ERROR(-20010, 'Connect as ITB2CTRF before creating voSkill objects');
    END IF;

    SELECT COUNT(*)
      INTO L_COLLISIONS
      FROM USER_OBJECTS
     WHERE OBJECT_NAME = 'VSK_CRITICAL_SKILL_THRESHOLDS';

    IF L_COLLISIONS > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Risk threshold objects already exist; inspect USER_OBJECTS');
    END IF;
END;
/

CREATE TABLE VSK_CRITICAL_SKILL_THRESHOLDS (
    PROJECT_ID VARCHAR2(36 CHAR) NOT NULL,
    SKILL_ID VARCHAR2(36 CHAR) NOT NULL,
    MIN_CONFIRMED_PEOPLE NUMBER(9) NOT NULL,
    ACTOR_ID VARCHAR2(36 CHAR) NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT VSK_PK_CRIT_SKILL_THR PRIMARY KEY (PROJECT_ID, SKILL_ID),
    CONSTRAINT VSK_FK_CST_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES VSK_PROJECTS (PROJECT_ID),
    CONSTRAINT VSK_FK_CST_SKILL FOREIGN KEY (SKILL_ID)
        REFERENCES VSK_SKILLS (SKILL_ID),
    CONSTRAINT VSK_CK_CST_MIN_PEOPLE CHECK (MIN_CONFIRMED_PEOPLE > 0)
);